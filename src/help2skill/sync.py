"""Keep a hand-edited SKILL.md in sync with the real CLI.

Two kinds of drift are detected:

* the generated reference block (between markers) is stale;
* hand-written text outside the block mentions a subcommand or option the CLI
  does not have, or uses an option at the wrong level.
"""

from __future__ import annotations

import difflib
import re
import shlex
from dataclasses import dataclass, field

from .model import Command
from .privacy import redact_home
from .render import SKILL_MAX_CHARS, render_index, render_markdown

BEGIN = "<!-- help2skill:begin (generated from the CLI; edit outside this block) -->"
END = "<!-- help2skill:end -->"
_BLOCK_RE = re.compile(r"<!-- help2skill:begin[^\n]*?-->\n?(.*?)<!-- help2skill:end -->", re.S)
_BEGIN_RE = re.compile(r"<!-- help2skill:begin([^\n(]*)")
_SETTING_RE = re.compile(r"([a-z-]+)=(\S+)")
_CODE_SPAN_RE = re.compile(r"`([^`\n]+)`")
_FENCE_RE = re.compile(r"^(```|~~~)")
_ALWAYS_OK = {"--help", "-h", "--llms"}
_STOP_TOKENS = {"|", "||", "&&", ";", ">", ">>", "<", "--"}
_ENV_ASSIGN_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*=")
# Launchers that run the real command, with their options that take a value.
_UV_RUN_VALUE_OPTS = {
    "--with", "--with-editable", "--with-requirements", "--python", "-p", "--project",
    "--directory", "--extra", "--group", "--only-group", "--package", "--env-file", "--from", "--index",
}  # fmt: skip
_RUNNER_PREFIXES = {("poetry", "run"), ("pdm", "run"), ("hatch", "run"), ("rye", "run"), ("pipx", "run")}

REFERENCE_FILE = "references/commands.md"
REFERENCE_HEADER = (
    "<!-- Generated by help2skill from the CLI. Do not edit: run `help2skill skill` to regenerate. -->\n\n"
)


@dataclass
class Settings:
    """Options used to generate a block, stored in its begin marker.

    ``help2skill check`` and :func:`help2skill.testing.assert_skill_in_sync` reuse
    them, so they never have to be repeated.
    """

    program: str | None = None
    max_chars: int | None = None
    hide_defaults: list[str] = field(default_factory=list)

    def marker(self) -> str:
        parts = []
        if self.program:
            parts.append(f"program={self.program}")
        if self.max_chars is not None:
            parts.append(f"max-chars={self.max_chars}")
        if self.hide_defaults:
            parts.append("hide-default=" + ",".join(self.hide_defaults))
        settings = " " + " ".join(parts) if parts else ""
        return f"<!-- help2skill:begin{settings} (generated from the CLI; edit outside this block) -->"


def read_settings(text: str) -> Settings:
    """Settings stored in the begin marker of ``text`` (empty if none)."""
    match = _BEGIN_RE.search(text)
    if not match:
        return Settings()
    values = dict(_SETTING_RE.findall(match.group(1)))
    max_chars = values.get("max-chars")
    return Settings(
        program=values.get("program"),
        max_chars=int(max_chars) if max_chars and max_chars.lstrip("-").isdigit() else None,
        hide_defaults=[v for v in values.get("hide-default", "").split(",") if v],
    )


@dataclass
class Problem:
    # missing-block | stale-block | missing-reference | stale-reference |
    # unknown-command | wrong-level-option | unknown-option | flag-value | invalid-choice
    kind: str
    message: str
    line: int | None = None

    def __str__(self) -> str:
        where = f"line {self.line}: " if self.line else ""
        return f"{where}{self.message} [{self.kind}]"


def wrap_block(generated: str, settings: Settings | None = None) -> str:
    begin = settings.marker() if settings else BEGIN
    return f"{begin}\n{generated.rstrip()}\n{END}\n"


def extract_block(text: str) -> str | None:
    match = _BLOCK_RE.search(text)
    return match.group(1) if match else None


def update_block(text: str, generated: str, settings: Settings | None = None) -> str:
    """Replace the generated block in ``text``, or append one if missing."""
    block = wrap_block(generated, settings)
    if _BLOCK_RE.search(text):
        return _BLOCK_RE.sub(lambda _: block.rstrip("\n"), text, count=1)
    return text.rstrip("\n") + "\n\n" + block


def skill_parts(cmd: Command, *, max_chars: int = SKILL_MAX_CHARS) -> tuple[str, str | None]:
    """Return the SKILL.md block and, for large CLIs, the reference file content."""
    full = redact_home(render_markdown(cmd, level=2))
    if max_chars <= 0 or len(full) <= max_chars or not cmd.is_group:
        return full, None
    hint = (
        f"Full reference for every command: [{REFERENCE_FILE}]({REFERENCE_FILE}). "
        "Read only the section of the command you need."
    )
    block = redact_home(render_index(cmd, level=2, hint=hint))
    # SKILL.md already has the index of every command; list only direct ones here.
    return block, REFERENCE_HEADER + redact_home(render_markdown(cmd, level=1, index=False))


def check(
    text: str,
    cmd: Command,
    *,
    max_chars: int = SKILL_MAX_CHARS,
    reference: str | None = None,
    scripts: tuple[str, ...] = (),
) -> list[Problem]:
    """Return every drift problem between ``text`` (a SKILL.md) and ``cmd``.

    ``reference`` is the content of ``references/commands.md`` if it exists.
    ``scripts`` are file names that also run the CLI (``python tool.py …``).
    """
    problems: list[Problem] = []
    current = extract_block(text)
    expected, expected_reference = skill_parts(cmd, max_chars=max_chars)
    if current is None:
        problems.append(Problem("missing-block", "no help2skill generated block found"))
    elif current.strip() != expected.strip():
        diff = "\n".join(
            difflib.unified_diff(
                current.strip().splitlines(),
                expected.strip().splitlines(),
                "SKILL.md",
                "CLI",
                lineterm="",
            )
        )
        message = "generated block is out of date"
        if _without_defaults(current) == _without_defaults(expected):
            message += (
                " (only default values differ: if they are computed at run time, such as a CPU "
                "count or a date, leave them out with --hide-default NAME)"
            )
        problems.append(Problem("stale-block", message + ":\n" + diff))
    if expected_reference is not None and reference is None:
        problems.append(Problem("missing-reference", f"{REFERENCE_FILE} is missing"))
    elif expected_reference is not None and reference is not None:
        if reference.strip() != expected_reference.strip():
            problems.append(Problem("stale-reference", f"{REFERENCE_FILE} is out of date"))
    problems.extend(check_references(_without_block(text), cmd, scripts=scripts))
    return problems


_DEFAULT_NOTE_RE = re.compile(r"default: [^;)]*")


def _without_defaults(text: str) -> str:
    return _DEFAULT_NOTE_RE.sub("default", text).strip()


def check_references(text: str, cmd: Command, *, scripts: tuple[str, ...] = ()) -> list[Problem]:
    """Check command lines in code spans and fenced blocks of hand-written text.

    Lines may run the CLI by its name, through a launcher (``uv run``,
    ``python -m``), or as a script: ``python path/NAME.py`` or ``./NAME.py``,
    where NAME is the program name or one of ``scripts``. Missing required
    arguments are reported only for lines in fenced blocks, since a code span in
    prose often names a command without its arguments.
    """
    problems = []
    for lineno, snippet, in_fence in _snippets(text):
        problems.extend(_check_invocation(snippet, cmd, lineno, complete=in_fence, scripts=scripts))
    return problems


def count_command_lines(text: str, program: str, *, scripts: tuple[str, ...] = ()) -> int:
    """How many hand-written lines (outside the generated block) run ``program``."""
    count = 0
    for _, snippet, _ in _snippets(_without_block(text)):
        try:
            tokens = shlex.split(snippet.strip().removeprefix("$ "), comments=True)
        except ValueError:
            continue
        if _strip_launchers(_join_placeholders(tokens), program, scripts):
            count += 1
    return count


def _without_block(text: str) -> str:
    # Keep line numbers stable by blanking the block instead of removing it.
    return _BLOCK_RE.sub(lambda m: "\n" * m.group(0).count("\n"), text)


def _snippets(text: str):
    in_fence = False
    pending: tuple[int, str] | None = None  # a command continued with a trailing backslash
    for lineno, line in enumerate(text.splitlines(), start=1):
        if _FENCE_RE.match(line.strip()):
            in_fence = not in_fence
            if pending:
                yield (*pending, True)
                pending = None
            continue
        if in_fence:
            if pending:
                lineno, line = pending[0], pending[1] + " " + line.strip()
                pending = None
            if line.rstrip().endswith("\\"):
                pending = (lineno, line.rstrip()[:-1])
                continue
            yield lineno, line, True
        else:
            for match in _CODE_SPAN_RE.finditer(line):
                yield lineno, match.group(1), False


def _check_invocation(
    snippet: str, root: Command, lineno: int, *, complete: bool = False, scripts: tuple[str, ...] = ()
) -> list[Problem]:
    snippet = snippet.strip().removeprefix("$ ")
    try:
        tokens = shlex.split(snippet, comments=True)
    except ValueError:
        return []
    tokens = _strip_launchers(_join_placeholders(tokens), root.name, scripts)
    if not tokens:
        return []
    return _Walker(root, lineno, complete=complete).run(tokens[1:])


class _Walker:
    """Follow one command line through the command tree, the way the parser would."""

    def __init__(self, root: Command, lineno: int, *, complete: bool = False) -> None:
        self.node = root
        self.ancestors = [root]
        self.lineno = lineno
        self.problems: list[Problem] = []
        self.positional = 0
        self.given = 0  # positional tokens given to the current command
        self.by_name: set[str] = set()  # arguments given as ``--name VALUE``
        # Report missing arguments only for whole command lines that were read to the end.
        self.complete = complete

    def report(self, kind: str, message: str) -> None:
        self.problems.append(Problem(kind, message, self.lineno))

    def run(self, tokens: list[str]) -> list[Problem]:
        i = 0
        finished = True
        while i < len(tokens):
            token = tokens[i]
            if token in _STOP_TOKENS:
                break
            if token in _ALWAYS_OK:
                self.complete = False  # --help needs no arguments
            if _PROSE_OPTION_RE.match(token):
                finished = False  # "-s/--short" names an option in prose; it is not a command line
                break
            if token.startswith("-") and token != "-":
                i = self.option(tokens, i)
                continue
            if not self.positional_token(token):
                finished = False
                break
            i += 1
        if finished and self.complete and not self.problems:
            self.check_missing_arguments()
        return self.problems

    def check_missing_arguments(self) -> None:
        node = self.node
        if node.is_group:
            return
        positional = [a for a in node.arguments if a.name not in self.by_name]
        missing = [a for a in positional[self.given :] if a.required]
        if missing:
            names = ", ".join(f"`{a.name.upper()}`" for a in missing)
            self.report("missing-argument", f"`{_path(node)}` needs {names}")

    # -- options ---------------------------------------------------------------
    def option(self, tokens: list[str], i: int) -> int:
        token = tokens[i]
        flag, has_value, value = token.partition("=")
        if flag in _ALWAYS_OK:
            return i + 1
        param = _find_option(self.node, flag)
        if param is None and self.enter_default_for(flag):
            return self.option(tokens, i)
        if param is None and not flag.startswith("--") and len(flag) > 2 and not has_value:
            return self.short_cluster(tokens, i)
        if param is None:
            self.misplaced_option(flag)
            # Skip a likely value so it is not mistaken for a subcommand.
            nxt = tokens[i + 1] if i + 1 < len(tokens) else None
            if not has_value and nxt is not None and not nxt.startswith("-") and self.node.get(nxt) is None:
                return i + 2
            return i + 1
        if param.is_flag:
            if has_value:
                self.report("flag-value", f"`{flag}` is a flag and takes no value")
            return i + 1
        if not param.is_option:
            self.by_name.add(param.name)
        if has_value:
            self.check_choice(param, value)
            return i + 1
        return self.consume_values(param, tokens, i + 1)

    def short_cluster(self, tokens: list[str], i: int) -> int:
        """``-vv``, ``-fq`` or ``-n5``: single-letter options written together."""
        token = tokens[i]
        for pos in range(1, len(token)):
            short = "-" + token[pos]
            param = _find_option(self.node, short)
            if param is None:
                self.misplaced_option(short, cluster=token)
                return i + 1
            if not param.is_flag:
                rest = token[pos + 1 :]
                if rest:
                    self.check_choice(param, rest)
                    return i + 1
                return self.consume_values(param, tokens, i + 1)
        return i + 1

    def consume_values(self, param, tokens: list[str], i: int) -> int:
        if param.value_tokens:
            count: int | None = len(param.value_tokens)
        elif isinstance(param.nargs, int) and param.nargs > 1:
            count = param.nargs
        elif param.nargs in ("*", "+", "?") or param.optional_value:
            count = None
        else:
            count = 1
        if count is None:
            limit = 1 if param.nargs == "?" or param.optional_value else len(tokens)
            taken = 0
            while i < len(tokens) and taken < limit and not tokens[i].startswith("-"):
                if tokens[i] in _STOP_TOKENS:
                    break
                self.check_choice(param, tokens[i])
                i += 1
                taken += 1
            return i
        for k in range(count):
            if i + k < len(tokens):
                if k == 0 or not param.value_tokens:
                    self.check_choice(param, tokens[i + k])
        return i + count

    def check_choice(self, param, value: str) -> None:
        if not param.choices or _is_placeholder(value):
            return
        allowed = param.choices
        if param.case_insensitive:
            ok = value.casefold() in {c.casefold() for c in allowed}
        else:
            ok = value in allowed
        if not ok:
            name = max(param.opts, key=len) if param.is_option else param.name.upper()
            self.report(
                "invalid-choice",
                f"`{value}` is not a valid value for `{name}` in `{_path(self.node)}` "
                f"(choose from: {', '.join(allowed)})",
            )

    def misplaced_option(self, flag: str, *, cluster: str | None = None) -> None:
        owner = next((a for a in self.ancestors if _find_option(a, flag)), None)
        if owner is not None:
            self.report(
                "wrong-level-option",
                f"`{flag}` belongs to `{_path(owner)}`, not `{_path(self.node)}` "
                "(place it before the subcommand)",
            )
            return
        below = next((c for c in self.node.walk() if c is not self.node and _find_option(c, flag)), None)
        if below is not None:
            self.report(
                "wrong-level-option",
                f"`{flag}` belongs to `{_path(below)}`, not `{_path(self.node)}` "
                f"(place it after `{below.path[-1]}`)",
            )
            return
        where = f" (in `{cluster}`)" if cluster else ""
        message = f"`{_path(self.node)}` has no option `{flag}`{where}"
        names = [o for p in self.node.options for o in (*p.opts, *p.secondary_opts)]
        message += _did_you_mean(flag, names)
        self.report("unknown-option", message)

    # -- positionals -------------------------------------------------------------
    def positional_token(self, token: str) -> bool:
        """Handle a non-option token; return False to stop checking the line."""
        node = self.node
        if node.is_group:
            child = node.get(token)
            if child is not None:
                self.enter(child)
                return True
            if token in node.hidden_subcommands:
                return False
            default = node.get(node.default_command) if node.default_command else None
            if default is not None:
                # The token is the first argument of the default subcommand.
                self.enter(default)
                return self.positional_token(token)
            if _is_placeholder(token):
                return False
            names = [c.name for c in node.subcommands] + [a for c in node.subcommands for a in c.aliases]
            self.report(
                "unknown-command",
                f"`{_path(node)}` has no subcommand `{token}`" + _did_you_mean(token, names),
            )
            return False
        # Leaf command: check the value against the matching argument's choices.
        if _is_placeholder(token):
            self.given += 1
            if self.positional < len(node.arguments) and not node.arguments[self.positional].multiple:
                self.positional += 1
            return True
        args = node.arguments
        self.given += 1
        if self.positional < len(args):
            arg = args[self.positional]
            self.check_choice(arg, token)
            if not arg.multiple:
                self.positional += 1
        return True

    def enter_default_for(self, flag: str) -> bool:
        """``tool --opt`` where ``--opt`` belongs to the group's default command.

        Groups with a default command (click-default-group) pass options they do
        not know to it, so ``llm --system x`` means ``llm prompt --system x``.
        """
        node = self.node
        default = node.get(node.default_command) if node.is_group and node.default_command else None
        if default is None:
            return False
        first_short = "-" + flag[1] if not flag.startswith("--") and len(flag) > 2 else None
        if _find_option(default, flag) is None and (
            first_short is None or _find_option(default, first_short) is None
        ):
            return False
        self.enter(default)
        return True

    def enter(self, child: Command) -> None:
        self.node = child
        self.ancestors.append(child)
        self.positional = 0
        self.given = 0
        self.by_name = set()


def _path(cmd: Command) -> str:
    return " ".join(cmd.path)


def _did_you_mean(word: str, candidates: list[str]) -> str:
    close = difflib.get_close_matches(word, candidates, n=1, cutoff=0.6)
    return f"; did you mean `{close[0]}`?" if close else ""


def _strip_launchers(tokens: list[str], root_name: str, scripts: tuple[str, ...] = ()) -> list[str]:
    """Drop ``VAR=x``, ``uv run …``, ``python -m mod`` etc. so the CLI name comes first.

    Returns an empty list when the line does not invoke ``root_name``.
    """
    i = 0
    while i < len(tokens):
        token = tokens[i]
        if token == root_name:
            return tokens[i:]
        if _is_script(token, root_name, scripts):
            return [root_name, *tokens[i + 1 :]]
        if re.fullmatch(r"python(\d+(\.\d+)?)?", token) and i + 1 < len(tokens) and tokens[i + 1] != "-m":
            j = i + 1
            while j < len(tokens) and tokens[j].startswith("-") and tokens[j] != "-m":
                j += 2 if tokens[j] in ("-X", "-W") else 1
            if j < len(tokens) and tokens[j] != "-m":
                if _is_script(tokens[j], root_name, scripts):
                    return [root_name, *tokens[j + 1 :]]
                return []
        if _ENV_ASSIGN_RE.match(token):
            i += 1
        elif token == "uv" and tokens[i + 1 : i + 3] == ["tool", "run"]:
            i = _skip_options(tokens, i + 3)
        elif (token == "uv" and tokens[i + 1 : i + 2] == ["run"]) or token == "uvx":
            i = _skip_options(tokens, i + (2 if token == "uv" else 1))
        elif tuple(tokens[i : i + 2]) in _RUNNER_PREFIXES:
            i = _skip_options(tokens, i + 2)
        elif re.fullmatch(r"python(\d+(\.\d+)?)?", token) and tokens[i + 1 : i + 2] == ["-m"]:
            module = tokens[i + 2] if i + 2 < len(tokens) else ""
            if module.replace("_", "-") != root_name.replace("_", "-"):
                return []
            return [root_name, *tokens[i + 3 :]]
        else:
            return []
    return []


def _join_placeholders(tokens: list[str]) -> list[str]:
    """``<thư mục đợt>`` is one placeholder even though the shell splits it."""
    joined: list[str] = []
    open_at: int | None = None
    for token in tokens:
        if open_at is not None:
            joined[open_at] += " " + token
            if token.endswith(">"):
                open_at = None
            continue
        joined.append(token)
        if token.startswith("<") and not token.endswith(">"):
            open_at = len(joined) - 1
    return joined


def _is_script(token: str, root_name: str, scripts: tuple[str, ...]) -> bool:
    """``tool.py``, ``./tool``, ``scripts/tool.py``: a file that runs the CLI."""
    if "/" not in token and "\\" not in token and not token.endswith(".py"):
        return False
    name = re.split(r"[/\\]", token)[-1]
    return name in scripts or name in (root_name, f"{root_name}.py")


def _skip_options(tokens: list[str], i: int) -> int:
    while i < len(tokens) and tokens[i].startswith("-"):
        takes_value = tokens[i] in _UV_RUN_VALUE_OPTS and "=" not in tokens[i]
        i += 2 if takes_value else 1
    return i


def _find_option(cmd: Command, flag: str):
    for p in cmd.options:
        if flag in p.opts or flag in p.secondary_opts:
            return p
    # Arguments that may also be written as options (cyclopts: ``--name VALUE``).
    for p in cmd.arguments:
        if flag in p.secondary_opts:
            return p
    return None


# "-s/--short" or "--json/--no-json": option names written as prose.
_PROSE_OPTION_RE = re.compile(r"^--?[\w-]+/--?[\w-]")
_PLACEHOLDER_PREFIXES = ("<", "{", "[", "$", "my_", "my-", "your_", "your-")


def _is_placeholder(token: str) -> bool:
    return (
        token.isupper()
        or token.lower().startswith(_PLACEHOLDER_PREFIXES)
        or token in {"...", "…"}
        or "|" in token  # "a|b|c": a choice written out in prose
    )
